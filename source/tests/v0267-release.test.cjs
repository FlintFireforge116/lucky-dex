'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const ROOT=path.resolve(__dirname,'..');
const gradle=fs.readFileSync(path.join(ROOT,'app/build.gradle'),'utf8');
const html=fs.readFileSync(path.join(ROOT,'app/src/main/assets/index.html'),'utf8');
const app=fs.readFileSync(path.join(ROOT,'app/src/main/assets/app-v0167.js'),'utf8');
const pkg=require(path.join(ROOT,'package.json'));
const lock=require(path.join(ROOT,'package-lock.json'));
assert.ok(Number((gradle.match(/versionCode\s+(\d+)/)||[])[1])>=267,'Android versionCode must remain at least 267');
const currentVersion=(gradle.match(/versionName\s+['"]([^'"]+)['"]/ )||[])[1];assert.ok(currentVersion&&currentVersion.localeCompare('0.26.7',undefined,{numeric:true})>=0,'Android version must remain at least v0.26.7');
assert.equal(pkg.version,currentVersion);
assert.equal(lock.version,currentVersion);
assert.equal(lock.packages[''].version,currentVersion);
assert.ok(html.includes(`v${currentVersion}`),'visible app version must match the current release');
const runtimeVersion=(app.match(/__LUCKYDEX_BUILD=['"]([^'"]+)['"]/)||[])[1];assert.ok(runtimeVersion&&runtimeVersion.localeCompare('0.26.7',undefined,{numeric:true})>=0,'runtime build marker must remain at v0.26.7 or later');
console.log('PASS v0.26.7+ release identity contract');
