const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const gradle=fs.readFileSync(path.join(root,'app/build.gradle'),'utf8');
const pkg=require(path.join(root,'package.json'));
const lock=require(path.join(root,'package-lock.json'));
const html=fs.readFileSync(path.join(root,'app/src/main/assets/index.html'),'utf8');
const app=fs.readFileSync(path.join(root,'app/src/main/assets/app-v0167.js'),'utf8');
const code=Number((gradle.match(/versionCode\s+(\d+)/)||[])[1]);
const name=(gradle.match(/versionName\s+['"]([^'"]+)['"]/ )||[])[1];
const parts=String(name||'0').split('.').map(Number);
assert.match(gradle,/applicationId\s+['"]com\.example\.luckydex['"]/);
assert.ok(code>=287,'release identity must never move backwards from v0.28.7');
assert.ok(parts[0]>0||parts[1]>28||(parts[1]===28&&parts[2]>=7),'versionName must be v0.28.7 or newer');
assert.equal(pkg.version,name);
assert.equal(lock.version,name);
assert.equal(lock.packages?.['']?.version,name);
assert.ok(html.includes(`v${name}`),'visible app version must match Gradle');
assert.match(app,new RegExp(`window\\.__LUCKYDEX_BUILD=['"]${name.replace(/\./g,'\\.')}['"]`));
console.log('PASS v0.28.7+ release identity remains compatible');
