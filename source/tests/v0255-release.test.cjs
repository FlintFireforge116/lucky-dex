const assert=require('assert');
const fs=require('fs');
const path=require('path');
const crypto=require('crypto');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const gradle=read('app/build.gradle');
const versionCode=Number((gradle.match(/versionCode\s+(\d+)/)||[])[1]);
assert(versionCode>=255,'versionCode must not regress below 255');
const versionName=(gradle.match(/versionName\s+'([^']+)'/)||[])[1];
assert(versionName&&versionName.localeCompare('0.25.5',undefined,{numeric:true})>=0,'versionName must not regress below 0.25.5');
assert(/applicationId\s+'com\.example\.luckydex'/.test(gradle),'applicationId must remain permanent');
const pkg=JSON.parse(read('package.json'));assert.equal(pkg.version,versionName);
const lock=JSON.parse(read('package-lock.json'));assert.equal(lock.version,versionName);assert.equal(lock.packages[''].version,versionName);
const core=read('app/src/main/assets/arcade-fossil-museum-core.js');
assert(/arcade\/fossil-museum-v025[5-9]\/items\//.test(core),'active fossil/museum catalogue must use v0.25.5+ audited art namespace');
assert(fs.existsSync(path.join(root,'app/src/main/assets/arcade/fossil-museum-v0255/manifest.json')));
assert(fs.existsSync(path.join(root,'app/src/main/assets/arcade/fossil-museum-v0255/SOURCES.md')));
const key=fs.readFileSync(path.join(root,'app/luckydex-dev.keystore'));
assert.equal(crypto.createHash('sha256').update(key).digest('hex'),'90de91cea469f0eec5fbd69389cf03adc94ced396fa2ec85e2a51d2365a4f6d3');
console.log('v0.25.5+ release compatibility contract passed');
