'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const gradle=fs.readFileSync(path.join(__dirname,'../app/build.gradle'),'utf8');
const pkg=JSON.parse(fs.readFileSync(path.join(__dirname,'../package.json'),'utf8'));
const lock=JSON.parse(fs.readFileSync(path.join(__dirname,'../package-lock.json'),'utf8'));
const app=fs.readFileSync(path.join(__dirname,'../app/src/main/assets/app-v0167.js'),'utf8');
const trade=fs.readFileSync(path.join(__dirname,'../app/src/main/assets/trade-v0163.js'),'utf8');
const workflow=fs.readFileSync(path.join(__dirname,'../.github/workflows/build-apk.yml'),'utf8');
assert.match(gradle,/applicationId\s+'com\.example\.luckydex'/,'Android applicationId is frozen');
const versionCode=Number((gradle.match(/versionCode\s+(\d+)/)||[])[1]);
const versionName=(gradle.match(/versionName\s+'([^']+)'/)||[])[1];
assert.ok(versionCode>=240,'v0.24 patch releases never lower Android versionCode below 240');
const versionParts=String(versionName||'').split('.').map(Number);assert.ok(versionParts[0]>0||versionParts[1]>=24,'release version never goes backwards from v0.24');
assert.equal(pkg.version,versionName,'package version matches Android versionName');
assert.equal(lock.version,versionName,'package-lock root version matches Android versionName');
assert.equal(lock.packages[''].version,versionName,'package-lock workspace version matches Android versionName');
assert.match(app,/localStorage\.getItem\('luckyDexSave'\)/,'save key remains luckyDexSave');
assert.match(workflow,/LUCKYDEX_KEYSTORE_BASE64/,'GitHub build still uses established keystore secret');
assert.match(gradle,/file\('luckydex-dev\.keystore'\)/,'Gradle signing file contract still targets luckydex-dev.keystore');
assert.match(gradle,/storeFile\s+(?:devKeystore|file\('luckydex-dev\.keystore'\))/,'Gradle uses the established signing file');
assert.match(trade,/if\(!state\.trade\.boards[^\n]+state\.trade\.boards = \{\}/,'legacy boards field is preserved/initialized');
assert.doesNotMatch(trade,/state\.trade\.boards\s*=\s*\{\};\s*state\.trade\.currentSlot/,'v0.24 does not destructively wipe legacy boards during migration');
assert.match(app,/ui:\s*\{\.\.\.base\.ui,\.\.\.\(raw\.ui\|\|\{\}\)/,'new UI state merges additively');
console.log('PASS v0.24 Android/save/signing compatibility contract');
