'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const gradle=read('app/build.gradle');
const html=read('app/src/main/assets/index.html');
const app=read('app/src/main/assets/app-v0167.js');
const pkg=JSON.parse(read('package.json'));
const lock=JSON.parse(read('package-lock.json'));
assert.match(gradle,/applicationId\s+'com\.example\.luckydex'/,'application ID must remain unchanged');
const code=Number((gradle.match(/versionCode\s+(\d+)/)||[])[1]);
const name=(gradle.match(/versionName\s+'([^']+)'/)||[])[1];
assert.ok(code>=273,'Android update must never regress below the v0.27.3 baseline');
assert.ok(name&&name.localeCompare('0.27.3',undefined,{numeric:true})>=0,'release should remain v0.27.3 or newer');
assert.equal(pkg.version,name,'package version should match Android versionName');
assert.equal(lock.version,name,'package-lock version should match Android versionName');
assert.equal(lock.packages[''].version,name,'package-lock root package version should match Android versionName');
assert.ok(html.includes(`v${name}`),'visible app version should match current release');
assert.ok(app.includes(`__LUCKYDEX_BUILD='${name}'`),'runtime build marker should match current release');
console.log('PASS v0.27.3+ update identity/version baseline');
