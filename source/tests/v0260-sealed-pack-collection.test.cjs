assert.match(app,/sealedPacks:\{\}/,'default state must own a sealed-pack inventory');
assert.match(app,/sealedPacks:\{\.\.\.\(raw\.sealedPacks\|\|\{\}\)\}/,'loadState must preserve/migrate sealed packs');
assert.match(app,/function giveSealedPackV0260\(/,'reusable sealed-pack grant helper must exist');
