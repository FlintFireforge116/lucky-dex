const assert=require('assert');
const platform=require('../app/src/main/assets/arcade-platform.js');
const session=require('../app/src/main/assets/arcade-session.js');
const achievements=require('../app/src/main/assets/achievements-v0341.js');
const base=platform.ensureArcadeState({});
assert.deepStrictEqual(base.magikarpSplash,{gamesPlayed:0,wins:0,podiums:0,bestScore:0,bestScores:{easy:0,normal:0,hard:0},winsByDifficulty:{easy:0,normal:0,hard:0},bestQuickChain:0});
const migrated=platform.ensureArcadeState({foo:{keep:1},magikarpSplash:{gamesPlayed:4,bestScore:17,bestScores:{hard:22},winsByDifficulty:{normal:2}}});
assert.deepStrictEqual(migrated.foo,{keep:1});
assert.strictEqual(migrated.magikarpSplash.gamesPlayed,4);
assert.deepStrictEqual(migrated.magikarpSplash.bestScores,{easy:0,normal:0,hard:22});
assert.deepStrictEqual(migrated.magikarpSplash.winsByDifficulty,{easy:0,normal:2,hard:0});
const malformed=platform.ensureArcadeState({keepMe:{yes:true},magikarpSplash:{bestScores:{easy:undefined,normal:NaN,hard:19},winsByDifficulty:{easy:null,normal:'bad',hard:undefined}}});
assert.deepStrictEqual(malformed.keepMe,{yes:true},'malformed migration must preserve unrelated Arcade data');
assert.deepStrictEqual(malformed.magikarpSplash.bestScores,{easy:0,normal:0,hard:19},'malformed bestScores must never leave undefined/NaN difficulty records');
assert.deepStrictEqual(malformed.magikarpSplash.winsByDifficulty,{easy:0,normal:0,hard:0},'malformed winsByDifficulty must normalize invalid values to zero');
assert.match(session.GAME_RULES.magikarpSplash.run,/20 seconds/i);
assert.match(session.GAME_RULES.magikarpSplash.run,/tim/i);
assert.match(session.GAME_RULES.magikarpSplash.reward,/Placement/i);
const st={arcade:{magikarpSplash:{wins:0,bestScore:0,bestQuickChain:0,winsByDifficulty:{hard:0}}}};
const rows=achievements.buildCoreAchievements(()=>st);
const by=Object.fromEntries(rows.map(x=>[x.id,x]));
for(const id of ['magikarp_first_win','magikarp_hard_win','magikarp_score_25','magikarp_quick_10'])assert.ok(by[id],id);
assert.deepStrictEqual(by.magikarp_first_win.reward,{coins:200});
assert.deepStrictEqual(by.magikarp_hard_win.reward,{coins:600,dust:30});
assert.deepStrictEqual(by.magikarp_score_25.reward,{coins:900,dust:60});
assert.deepStrictEqual(by.magikarp_quick_10.reward,{coins:700,dust:40});
for(const id of ['magikarp_first_win','magikarp_hard_win','magikarp_score_25','magikarp_quick_10'])assert.strictEqual(by[id].progress()[0],0,`${id} missing values must be zero-safe`);
console.log('v0.37.0 Magikarp state/achievement tests passed');
