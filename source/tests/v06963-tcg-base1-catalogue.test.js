'use strict';
const assert=require('node:assert/strict');
const base=require('../app/src/main/assets/tcg-classic-base1.js');

assert.equal(base.SET.id,'base1');
assert.equal(base.SET.name,'Base Set');
assert.equal(base.CARDS.length,102,'Base Set manifest must contain every numbered card');
assert.equal(new Set(base.CARDS.map(c=>c.id)).size,102,'Base Set IDs must be unique');
assert.equal(base.cardById('base1-4').name,'Charizard');
assert.equal(base.cardById('base1-58').name,'Pikachu');
assert.equal(base.cardById('base1-96').name,'Double Colorless Energy');
assert.equal(base.cardById('base1-102').name,'Water Energy');
assert.equal(base.cardById('base1-70').kind,'trainer');
assert.equal(base.cardById('base1-97').kind,'energy');
assert.equal(base.cardById('base1-97').basicEnergy,true);
assert.equal(base.cardById('base1-97').battleEnabled,false,'basic Energy is generated by the LuckyDex Energy Zone, not put in a 30-card deck');
assert.equal(base.cardById('base1-96').specialEnergy,true);
assert.equal(base.cardById('base1-96').battleEnabled,true,'Double Colorless is FULL once card-valued Special Energy attachment/discard semantics exist');
assert.equal(base.cardById('base1-96').support.status,'FULL');
assert.equal(base.cardById('base1-4').support.status,'FULL');
assert.equal(base.cardById('base1-4').battleEnabled,true);

const simple=base.registerDetails({
 id:'base1-7',name:'Hitmonchan',supertype:'Pokémon',subtypes:['Basic'],hp:'70',types:['Fighting'],
 attacks:[{name:'Jab',cost:['Fighting'],damage:'20',text:''},{name:'Special Punch',cost:['Fighting','Fighting','Colorless'],damage:'40',text:''}],
 weaknesses:[{type:'Psychic',value:'×2'}],retreatCost:['Colorless','Colorless']
});
assert.equal(simple.battleEnabled,true);
assert.equal(simple.support.status,'FULL');
assert.equal(simple.stage,'Basic');
assert.equal(simple.hp,70);
assert.equal(simple.attacks[0].cost,'F');
assert.equal(simple.attacks[1].cost,'FFC');

const awkward=base.registerDetails({
 id:'base1-1',name:'Alakazam',supertype:'Pokémon',subtypes:['Stage 2'],hp:'80',types:['Psychic'],evolvesFrom:'Kadabra',
 abilities:[{name:'Damage Swap',type:'Pokémon Power',text:'As often as you like during your turn, move damage counters around.'}],
 attacks:[{name:'Confuse Ray',cost:['Psychic','Psychic','Psychic'],damage:'30',text:'Flip a coin. If heads, the Defending Pokémon is now Confused.'}],
 retreatCost:['Colorless','Colorless','Colorless']
});
assert.equal(awkward.battleEnabled,false,'unknown Pokémon Power must block the entire card');
assert.match(awkward.support.reasons.join(' '),/Damage Swap|Pokémon Power|Unimplemented/i);

const rows=base.projectOwnedCards({
 a:{id:'base1-7',name:'Hitmonchan',source:'tcg',setId:'base1',count:2,image:'x'},
 b:{id:'base1-4',name:'Charizard',source:'tcg',setId:'base1',count:1},
 c:{id:'A1-001',name:'Bulbasaur',source:'tcgp',setId:'A1',count:9},
 d:{id:'base2-1',name:'Clefable',source:'tcg',setId:'base2',count:2}
});
assert.equal(rows.length,2);
assert.equal(rows.find(r=>r.gameplayId==='base1-7').quantity,2);
assert.equal(rows.find(r=>r.gameplayId==='base1-7').battleEnabled,true);
assert.equal(rows.find(r=>r.gameplayId==='base1-4').battleEnabled,true);

console.log('v0.69.63 Base Set catalogue tests passed');
