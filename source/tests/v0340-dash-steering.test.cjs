'use strict';
const assert=require('node:assert/strict'),path=require('node:path');
const a=path.resolve(__dirname,'../app/src/main/assets');
global.LuckyDexDashConfig=require(path.join(a,'arcade-dash-config.js'));
global.LuckyDexAdventureSpecies=require(path.join(a,'adventure/adventure-species.js'));
global.LuckyDexDashCourse=require(path.join(a,'arcade-dash-course.js'));
const dash=require(path.join(a,'arcade-dash.js'));
function race(){const r=dash.createRaceState({key:'4:n',id:4,name:'Charmander',baseSpeed:65,level:8},[],{seed:7,difficulty:'easy'});r.phase='racing';r.course.objects=[];r.racers=r.racers.slice(0,1);return r;}
const r=race(),p=r.racers[0];
dash.stepRace(r,1/60,{steer:1,sprint:false});
assert(p.laneVisual>1,'steering responds on the first simulated frame');
assert(p.laneVisual<1.2,'steering uses smooth movement instead of teleporting');
const first=p.laneVisual;
for(let i=0;i<5;i++)dash.stepRace(r,1/60,{steer:1});
assert(p.laneVisual>first,'continuous held steering advances the lateral position');
assert(p.laneVisual<2,'short holds allow fine corrections before reaching the edge');
const release=p.laneVisual;
for(let i=0;i<20;i++)dash.stepRace(r,1/60,{steer:0});
assert(Math.abs(p.laneVisual-release)<1e-8,'release holds position without queued movement');
dash.stepRace(r,1/60,{steer:-1});assert(p.laneVisual<release,'reversing responds on the next frame');
for(let i=0;i<180;i++)dash.stepRace(r,1/60,{steer:-1});
assert.equal(p.laneVisual,0,'held steering clamps at the left edge');
for(let i=0;i<180;i++)dash.stepRace(r,1/60,{steer:1});
assert.equal(p.laneVisual,2,'held steering clamps at the right edge');
const legacy=race();
for(let i=0;i<120;i++)dash.stepRace(legacy,1/60,{targetLane:0});
assert.equal(legacy.racers[0].laneVisual,0,'existing targetLane API remains compatible');
for(let i=0;i<120;i++)dash.stepRace(legacy,1/60,{targetLane:2});
assert.equal(legacy.racers[0].laneVisual,2,'AI/legacy targetLane control remains compatible in both directions');
console.log('PASS immediate continuous steering, fine corrections, deterministic release, edge bounds and legacy targetLane');
