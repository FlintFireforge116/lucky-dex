const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const crypto=require('node:crypto');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const gradle=read('app/build.gradle');
assert.match(gradle,/applicationId\s+'com\.example\.luckydex'/,'applicationId must stay permanent');
const versionCode=Number((gradle.match(/versionCode\s+(\d+)/)||[])[1]);
assert(versionCode>=256,'versionCode must not regress below 256');
const versionName=(gradle.match(/versionName\s+'([^']+)'/)||[])[1];
assert(versionName&&versionName.localeCompare('0.25.6',undefined,{numeric:true})>=0,'versionName must not regress below 0.25.6');
assert.equal(JSON.parse(read('package.json')).version,versionName);
const lock=JSON.parse(read('package-lock.json'));
assert.equal(lock.version,versionName);
assert.equal(lock.packages[''].version,versionName);
const key=fs.readFileSync(path.join(root,'app/luckydex-dev.keystore'));
assert.equal(crypto.createHash('sha256').update(key).digest('hex'),'90de91cea469f0eec5fbd69389cf03adc94ced396fa2ec85e2a51d2365a4f6d3');
console.log('PASS v0.25.6 release contract');
