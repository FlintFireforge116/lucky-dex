const assert=require('assert');
const fs=require('fs');
const gradle=fs.readFileSync('app/build.gradle','utf8');
const html=fs.readFileSync('app/src/main/assets/index.html','utf8');
const app=fs.readFileSync('app/src/main/assets/app-v0167.js','utf8');
const pkg=JSON.parse(fs.readFileSync('package.json','utf8'));
const lock=JSON.parse(fs.readFileSync('package-lock.json','utf8'));
assert.match(gradle,/applicationId 'com\.example\.luckydex'/,'Android application ID must remain upgrade-compatible');
assert.match(gradle,/versionCode 29[2-9]\b|versionCode [3-9][0-9]{2,}\b/,'post-v0.29.1 builds must retain an Android versionCode of at least 292');
const versionName=(gradle.match(/versionName '(\d+)\.(\d+)\.(\d+)'/)||[]).slice(1).map(Number);
assert.equal(versionName.length,3,'Android versionName must remain semantic');
assert.ok(versionName[0]>0 || versionName[1]>29 || (versionName[1]===29 && versionName[2]>=1),'post-v0.29.1 builds must not regress below v0.29.1');
const packageVersion=pkg.version.split('.').map(Number);
assert.equal(packageVersion.length,3);
assert.ok(packageVersion[0]>0 || packageVersion[1]>29 || (packageVersion[1]===29 && packageVersion[2]>=1),'package version must not regress below v0.29.1');
assert.strictEqual(lock.version,pkg.version);
assert.strictEqual(lock.packages[''].version,pkg.version);
assert.ok(html.includes(`v${pkg.version}`),'visible UI version must match package version');
assert.ok(app.includes(`__LUCKYDEX_BUILD='${pkg.version}'`),'runtime build marker must match package version');
console.log('v0.29.1+ release compatibility identity verified');
