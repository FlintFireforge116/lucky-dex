'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const pkg=JSON.parse(read('package.json'));
const lock=JSON.parse(read('package-lock.json'));
const gradle=read('app/build.gradle');
const html=read('app/src/main/assets/index.html');
const app=read('app/src/main/assets/app-v0167.js');
const versionCode=Number((gradle.match(/versionCode\s+(\d+)/)||[])[1]);
const versionName=(gradle.match(/versionName '([^']+)'/)||[])[1];
assert.ok(versionCode>=353,'release remains at or above the v0.35.3 release-ending hotfix floor');
assert.ok(versionName.localeCompare('0.35.3',undefined,{numeric:true})>=0,'versionName preserves v0.35.3 or later');
assert.equal(pkg.version,versionName);
assert.equal(lock.version,versionName);
assert.equal(lock.packages[''].version,versionName);
assert.match(html,new RegExp(`v${versionName.replace(/\./g,'\\.')}`));
assert.ok(app.includes(`window.__LUCKYDEX_BUILD='${versionName}'`));
assert.match(gradle,/applicationId ['"]com\.example\.luckydex['"]/,'app id remains stable for in-place update');
console.log('PASS v0.35.3+ release-ending hotfix floor');
