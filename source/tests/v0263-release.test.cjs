'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const crypto=require('node:crypto');
const ROOT=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(ROOT,p),'utf8');
const gradle=read('app/build.gradle');
const pkg=JSON.parse(read('package.json'));
const lock=JSON.parse(read('package-lock.json'));
const html=read('app/src/main/assets/index.html');
const app=read('app/src/main/assets/app-v0167.js');
assert.match(gradle,/applicationId\s+['"]com\.example\.luckydex['"]/);
const versionCode=Number((gradle.match(/versionCode\s+(\d+)/)||[])[1]);
const currentVersion=(gradle.match(/versionName\s+['"]([^'"]+)['"]/ )||[])[1];
assert.ok(versionCode>=263,'release must not regress below v0.26.3');
assert.ok(currentVersion&&currentVersion.localeCompare('0.26.3',undefined,{numeric:true})>=0,'versionName must not regress below v0.26.3');
assert.equal(pkg.version,currentVersion);
assert.equal(lock.version,currentVersion);
assert.equal(lock.packages[''].version,currentVersion);
assert.ok(html.includes(`v${currentVersion}`),'visible version must match Android versionName');
assert.match(app,new RegExp(`__LUCKYDEX_BUILD=['"]${currentVersion.replace(/\./g,'\\.')}[^'"]*['"]`),'runtime build marker must match current version');
const key=fs.readFileSync(path.join(ROOT,'app/luckydex-dev.keystore'));
assert.equal(crypto.createHash('sha256').update(key).digest('hex'),'90de91cea469f0eec5fbd69389cf03adc94ced396fa2ec85e2a51d2365a4f6d3');
console.log('PASS v0.26.3+ release identity/signing contract');
