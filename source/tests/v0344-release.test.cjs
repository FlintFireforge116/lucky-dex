'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const gradle=fs.readFileSync(path.join(root,'app/build.gradle'),'utf8');
const html=fs.readFileSync(path.join(root,'app/src/main/assets/index.html'),'utf8');
const app=fs.readFileSync(path.join(root,'app/src/main/assets/app-v0167.js'),'utf8');
const pkg=JSON.parse(fs.readFileSync(path.join(root,'package.json'),'utf8'));
const lock=JSON.parse(fs.readFileSync(path.join(root,'package-lock.json'),'utf8'));
const versionCode=Number((gradle.match(/versionCode\s+(\d+)/)||[])[1]);
const versionName=(gradle.match(/versionName '([^']+)'/)||[])[1];
assert.ok(versionCode>=344,'Android versionCode must preserve v0.34.4 or later');
assert.ok(versionName.localeCompare('0.34.4',undefined,{numeric:true})>=0,'Android versionName must preserve v0.34.4 or later');
assert.equal(pkg.version,versionName);
assert.equal(lock.version,versionName);
assert.equal(lock.packages[''].version,versionName);
assert.match(html,new RegExp(`v${versionName.replace(/\./g,'\\.')}`));
assert.ok(app.includes(`window.__LUCKYDEX_BUILD='${versionName}'`));
console.log('PASS v0.34.4+ release compatibility');
