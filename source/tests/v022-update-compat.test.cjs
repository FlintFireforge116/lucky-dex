const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.join(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const gradle=read('app/build.gradle');
const activity=read('app/src/main/java/com/example/luckydex/MainActivity.java');
const app=read('app/src/main/assets/app-v0167.js');
const platform=read('app/src/main/assets/arcade-platform.js');
const workflow=read('.github/workflows/build-apk.yml');
assert.match(gradle,/applicationId\s+['"]com\.example\.luckydex['"]/,'package id must remain update-compatible');
const versionCode=Number((gradle.match(/versionCode\s+(\d+)/)||[])[1]);
assert.ok(versionCode>=232,'versionCode must never roll back below the established update baseline');
const versionName=(gradle.match(/versionName\s+['"]([^'"]+)['"]/ )||[])[1];
assert.ok(versionName,'versionName must remain present');
assert(activity.includes('file:///android_asset/index.html'),'WebView origin must remain unchanged');
assert(app.includes("localStorage.getItem('luckyDexSave')"),'existing LuckyDex save key must still load');
assert(app.includes("localStorage.setItem('luckyDexSave'"),'existing LuckyDex save key must still persist');
assert(app.includes('bestHeadIt')||platform.includes('bestHeadIt'),'legacy Head It save field must remain tolerated');
assert(workflow.includes('LUCKYDEX_KEYSTORE_BASE64'),'CI must support restoring the original signing identity');
assert(!workflow.includes('rm -f app/luckydex-dev.keystore'),'workflow must not deliberately discard restored signer');
console.log('PASS update/save compatibility invariants at versionCode',versionCode);
