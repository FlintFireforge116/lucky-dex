l.recordRace(cup,r1);l.recordRace(cup,r2);l.recordRace(cup,r3);
assert.strictEqual(cup.raceIndex,3);
assert.deepStrictEqual(cup.entrants.map(x=>x.places.length),[3,3,3,3,3,3]);
assert.strictEqual(cup.entrants.find(x=>x.key==='p').points,26);
assert.strictEqual(cup.entrants.find(x=>x.key==='a1').points,22);
assert.deepStrictEqual(cup.aiRacerKeys,['a1','a2','a3','a4','a5']);
assert.deepStrictEqual(l.standings(cup).map(x=>x.key),['p','a1','a2','a3','a4','a5']);
const tied=l.createCup({type:'water',difficulty:'easy',player,aiRacers:ai,seed:9});
