const path=require('path');
global.LuckyDexDashConfig=require(path.resolve(__dirname,'../app/src/main/assets/arcade-dash-config.js'));
const modPath=path.resolve(__dirname,'../app/src/main/assets/arcade-dash-league.js');
delete require.cache[modPath];
const l=require(modPath);
const player={key:'p',name:'Player'};
const ai=[1,2,3,4,5].map(n=>({key:`a${n}`,name:`AI ${n}`}));
const cup=l.createCup({type:'fire',difficulty:'normal',player,aiRacers:ai,seed:123});
assert.strictEqual(cup.type,'fire');
assert.strictEqual(cup.difficulty,'normal');
assert.strictEqual(cup.raceIndex,0);
assert.deepStrictEqual(cup.entrants.map(x=>x.key),['p','a1','a2','a3','a4','a5']);
assert.deepStrictEqual(cup.entrants.map(x=>x.points),[0,0,0,0,0,0]);
assert.strictEqual(cup.completionHandled,false);
assert.deepStrictEqual([1,2,3,4,5,6].map(l.pointsForPlace),[10,6,4,3,2,1]);
