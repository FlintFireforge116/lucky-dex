'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const ROOT=path.resolve(__dirname,'..');
const assets=path.join(ROOT,'app/src/main/assets');
const artPath=path.join(assets,'booster-art-v0260.js');
assert.ok(fs.existsSync(artPath),'local booster-art runtime must exist');
const artDir=path.join(assets,'booster-art-v0260');
const files=fs.readdirSync(artDir).filter(n=>/\.(?:webp|png|jpe?g)$/i.test(n));
assert.equal(files.length,144,'v0.26.4 must ship the complete audited 144-packshot physical artwork set in the source/APK');
const manifest=JSON.parse(fs.readFileSync(path.join(assets,'booster-art-index-v0260.json'),'utf8'));
assert.equal(manifest.schema,2,'booster manifest must carry audited ID/name aliases');
assert.equal(Object.keys(manifest.byId||{}).length,144,'every bundled packshot needs an explicit source-set assignment');
assert.equal(manifest.byName?.jungle,'booster-art-v0260/base2.webp','Jungle must be assigned explicitly by display name');
assert.equal(manifest.byName?.['ruby sapphire'],'booster-art-v0260/ex1.webp','Ruby & Sapphire must be assigned explicitly by display name');
const builder=fs.readFileSync(path.join(ROOT,'scripts/build-booster-art-index.py'),'utf8');
assert.doesNotMatch(builder,/urllib|urlopen|raw\.githubusercontent|git\s+fetch/i,'APK booster-art verification must be fully local and network-independent');
assert.match(builder,/NON_BOOSTER_NO_ART/,'audit must explicitly distinguish the small known non-booster catalogue rows');
assert.match(builder,/verify_image_signatures/,'every packaged packshot must receive an integrity check');
console.log('PASS v0.26.4 complete local booster asset bundle');
