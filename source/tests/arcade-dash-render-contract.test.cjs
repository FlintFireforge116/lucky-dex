const assert=require('assert');
const fs=require('fs');
const path=require('path');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const html=read('app/src/main/assets/index.html');
const js=read('app/src/main/assets/arcade-dash.js');
const css=read('app/src/main/assets/arcade-dash.css');
assert.ok(/id="dashCanvas"\s+width="540"\s+height="720"/.test(html),'portrait canvas must be 540x720');
const rr=(js.match(/function renderRace\(\)[\s\S]*?function renderHud/)||[])[0]||'';
assert.ok(rr.includes('renderer.drawScene(')&&read('app/src/main/assets/arcade-dash-renderer.js').includes('worldToY(')&&read('app/src/main/assets/arcade-dash-renderer.js').includes('laneToX('),'renderer uses top-down helpers');
assert.ok(!rr.includes('finishX')&&!rr.includes('laneY=['),'horizontal finish/lane mapping removed');
const dr=read('app/src/main/assets/arcade-dash-renderer.js');
assert.ok(dr.includes('imageSmoothingEnabled=false'),'pixel smoothing disabled');
assert.ok(dr.includes('racerVisualScale('),'racer draw uses 96-112px helper');
assert.ok(!dr.includes("racer.name,x,y-")&&!dr.includes("'YOU':racer.name"),'AI name labels are not painted');
assert.ok(dr.includes('isPlayer')&&(dr.includes('marker')||dr.includes('cursor')||dr.includes('ring')),'player has marker treatment');
const dobj=dr;
assert.ok(dobj.includes('obj.effect')&&dobj.includes('assets.descriptor('),'themed skin/effect drives object visuals');
assert.ok(!html.includes('dashHudSprite')&&!html.includes('dashHudName')&&!html.includes('dashHudSpeed'),'race HUD only carries compact core info');
assert.ok(html.includes('id="dashLeftBtn"')&&html.includes('id="dashSprintBtn"')&&html.includes('id="dashRightBtn"'));
assert.ok(css.includes('overflow:hidden')&&css.includes('100dvh'),'mobile Dash view prevents internal page scroll');
assert.ok(css.includes('grid-template-columns:1fr 1.25fr 1fr'),'controls stay in one bottom row');
assert.ok(dr.includes('obj.consumed'),'consumed pickups are omitted from the active scene immediately');
assert.ok(js.includes('positionSignal')&&js.includes('finalStretch'),'race feedback includes position changes and final stretch');
assert.ok(dr.includes('safeLaneWidth'),'authored course width metadata affects the rendered road');
console.log('PASS Dash v2 top-down renderer source contract');
