'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const root=path.join(__dirname,'..');
const pkg=require('../package.json');
const lock=require('../package-lock.json');
const gradle=fs.readFileSync(path.join(root,'app/build.gradle'),'utf8');
const html=fs.readFileSync(path.join(root,'app/src/main/assets/index.html'),'utf8');
const app=fs.readFileSync(path.join(root,'app/src/main/assets/app-v0167.js'),'utf8');
const parts=pkg.version.split('.').map(Number);
assert.ok(parts[0]>0||parts[1]>35||(parts[1]===35&&parts[2]>=6),'release remains v0.35.6 or newer');
assert.equal(lock.version,pkg.version);
assert.equal(lock.packages[''].version,pkg.version);
const code=Number((gradle.match(/versionCode (\d+)/)||[])[1]);
assert.ok(code>=356);
assert.match(gradle,new RegExp(`versionName '${pkg.version.replace(/\./g,'\\.')}'`));
assert.match(html,new RegExp(`v${pkg.version.replace(/\./g,'\\.')}`));
assert.match(app,new RegExp(`__LUCKYDEX_BUILD='${pkg.version.replace(/\./g,'\\.')}'`));
console.log('PASS v0.35.6+ release identity');
