const assert=require('assert');
const fs=require('fs');
const path=require('path');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const gradle=read('app/build.gradle');
const html=read('app/src/main/assets/index.html');
const app=read('app/src/main/assets/app-v0167.js');
const pkg=JSON.parse(read('package.json'));
const lock=JSON.parse(read('package-lock.json'));
assert.match(gradle,/applicationId 'com\.example\.luckydex'/);
assert.ok(Number((gradle.match(/versionCode\s+(\d+)/)||[])[1])>=300);
const current=(gradle.match(/versionName '([^']+)'/)||[])[1];assert.ok(current.localeCompare('0.30.0',undefined,{numeric:true})>=0);
assert.strictEqual(pkg.version,current);
assert.strictEqual(lock.version,current);
assert.strictEqual(lock.packages[''].version,current);
assert.ok(html.includes('v'+current));
assert.ok(app.includes("window.__LUCKYDEX_BUILD='"+current+"'"));
assert.match(gradle,/luckydex-dev\.keystore/);
const config=html.indexOf('arcade-dash-config.js'),league=html.indexOf('arcade-dash-league.js'),course=html.indexOf('arcade-dash-course.js'),runtime=html.indexOf('arcade-dash.js');
assert.ok(config>0&&league>config&&course>league&&runtime>course,'Dash v2 scripts load in dependency order');
console.log('PASS LuckyDex v0.30.0 release identity and Dash v2 dependency order');
