'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const root=path.resolve(__dirname,'..');
const gradle=fs.readFileSync(path.join(root,'app/build.gradle'),'utf8');
const pkg=JSON.parse(fs.readFileSync(path.join(root,'package.json'),'utf8'));
const lock=JSON.parse(fs.readFileSync(path.join(root,'package-lock.json'),'utf8'));
const html=fs.readFileSync(path.join(root,'app/src/main/assets/index.html'),'utf8');
const app=fs.readFileSync(path.join(root,'app/src/main/assets/app-v0167.js'),'utf8');
assert.match(gradle,/applicationId\s+'com\.example\.luckydex'/,'application ID must remain unchanged');
const code=Number((gradle.match(/versionCode\s+(\d+)/)||[])[1]);
const name=(gradle.match(/versionName\s+'([^']+)'/)||[])[1];
assert.ok(code>=272,'Android update must never regress below the v0.27.2 baseline');
assert.ok(name&&name.localeCompare('0.27.2',undefined,{numeric:true})>=0,'release should remain v0.27.2 or newer');
assert.equal(pkg.version,name,'package version should match Android versionName');
assert.equal(lock.version,name,'package-lock version should match Android versionName');
assert.equal(lock.packages[''].version,name,'package-lock root package version should match Android versionName');
assert.ok(html.includes(`v${name}`),'visible app version should match current release');
assert.match(app,new RegExp(`__LUCKYDEX_BUILD='${name.replaceAll('.', '\\.')}''`.replace("''","'")),'runtime build marker should match current release');
console.log('PASS v0.27.2+ update identity/version baseline');
