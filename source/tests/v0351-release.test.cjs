'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs'),path=require('node:path');
const root=path.join(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const gradle=read('app/build.gradle'),html=read('app/src/main/assets/index.html'),app=read('app/src/main/assets/app-v0167.js'),world=read('app/src/main/assets/arcade-world.js');
const pkg=JSON.parse(read('package.json')),lock=JSON.parse(read('package-lock.json'));
assert.match(gradle,/applicationId 'com\.example\.luckydex'/);
const versionCode=Number((gradle.match(/versionCode\s+(\d+)/)||[])[1]);
const versionName=(gradle.match(/versionName '([^']+)'/)||[])[1];
assert.ok(versionCode>=351,'release remains at or above the solo Ekans score-attack floor');
assert.ok(versionName.localeCompare('0.35.1',undefined,{numeric:true})>=0,'versionName preserves v0.35.1 or later');
assert.equal(pkg.version,versionName);
assert.equal(lock.version,versionName);
assert.equal(lock.packages[''].version,versionName);
assert.match(html,new RegExp(`v${versionName.replace(/\./g,'\\.')}`));
assert.ok(app.includes(`window.__LUCKYDEX_BUILD='${versionName}'`));
for(const id of ['amieGarden','goldenrod','celadonPrize','lilycoveContest','oreburghMuseum','ruinsAlph','indigoQuiz','dashCourse','stadiumKidsClub'])assert.match(world,new RegExp(`id:"${id}"`));
console.log('PASS v0.35.1+ solo Ekans release floor and Arcade preservation');
